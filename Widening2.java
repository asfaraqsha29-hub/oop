public class Widening2{
	
	public static void main(String args[]){
		
		int marks=88;
		long longMarks=marks;
		float floatMarks=marks;
		double doubleMarks=marks;
		
		System.out.println("Int :"+marks);
		System.out.println("Long :"+longMarks);
		System.out.println("Float :"+floatMarks);
		System.out.println("Double :"+doubleMarks);
	}
}

		
		